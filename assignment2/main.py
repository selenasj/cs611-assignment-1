"""Local entry point; the Airflow DAG calls the same functions."""

from __future__ import annotations

import argparse
import json

import pandas as pd

from utils.data_pipeline import prepare_datamart
from utils.model_pipeline import monitor_as_of, score_cohort, score_both_strategies, train_and_select
from utils.governance import (approve_model, promote_model, rollback_model,
                              registry_status, simulate_review_and_promote,
                              prepare_historical_rebuild)
from utils.reporting import render_monitoring


def run_one(as_of: str, force_train: bool = False) -> dict:
    prepare_datamart()
    trained = train_and_select(as_of, force=force_train)
    reviewed = simulate_review_and_promote(as_of)
    scored = score_both_strategies(as_of)
    monitored = monitor_as_of(as_of)
    report = render_monitoring(as_of)
    return {"trained": trained, "reviewed": reviewed, "scored": scored,
            "monitored": monitored, "report": report}


def main() -> None:
    parser = argparse.ArgumentParser(description="CS611 Assignment 2 pipeline")
    parser.add_argument("command", choices=["prepare", "train", "score", "monitor", "report", "run", "backfill",
                                            "approve", "promote", "rollback", "registry-status"])
    parser.add_argument("--as-of", help="First day of month, YYYY-MM-DD")
    parser.add_argument("--start", default="2024-06-01")
    parser.add_argument("--end", default="2025-08-01")
    parser.add_argument("--force-train", action="store_true",
                        help="Rebuild saved models; use with backfill to refresh downstream outputs")
    parser.add_argument("--scope", choices=["historical", "production"], default="production",
                        help="Manual governance and standalone scoring default to production")
    parser.add_argument("--model-version")
    parser.add_argument("--reviewer")
    parser.add_argument("--reason")
    args = parser.parse_args()
    if args.force_train and args.command != "backfill":
        parser.error("--force-train requires the full backfill to rebuild simulated decisions and outputs")
    if args.force_train and (args.start != "2024-06-01" or args.end != "2025-08-01"):
        parser.error("A forced rebuild must cover the complete June 2024-August 2025 replay")
    if args.command == "prepare":
        result = prepare_datamart()
    elif args.command == "registry-status":
        result = registry_status(args.scope)
    elif args.command in {"approve", "promote", "rollback"}:
        if not all([args.as_of, args.model_version, args.reviewer, args.reason]):
            parser.error("Governance commands require --as-of, --model-version, --reviewer and --reason")
        if args.scope != "production":
            parser.error("Manual commands use production; historical approvals are generated by backfill")
        operation = {"approve": approve_model, "promote": promote_model, "rollback": rollback_model}[args.command]
        result = operation(args.model_version, args.as_of, args.reviewer, args.reason, args.scope)
    elif args.command == "backfill":
        if args.force_train:
            prepare_historical_rebuild()
        result = []
        for date in pd.date_range(args.start, args.end, freq="MS"):
            row = run_one(date.strftime("%Y-%m-%d"), force_train=args.force_train)
            result.append({"as_of_date": date.strftime("%Y-%m-%d"),
                           "model_status": row["trained"]["status"],
                           "scored_rows": row["scored"]["monthly_selected"]["rows"],
                           "fixed_comparator_rows": row["scored"]["fixed_june_2024"]["rows"],
                           "mature_cohorts": row["monitored"]["mature_cohorts"]})
            print(json.dumps(result[-1]), flush=True)
    else:
        if not args.as_of:
            parser.error("--as-of is required")
        if args.command == "train":
            result = train_and_select(args.as_of, force=args.force_train)
        elif args.command == "run":
            result = run_one(args.as_of, force_train=args.force_train)
        elif args.command == "score":
            result = score_cohort(args.as_of, scope=args.scope)
        else:
            result = {
                "monitor": monitor_as_of,
                "report": render_monitoring,
            }[args.command](args.as_of)
    print(json.dumps(result, default=str, indent=2))


if __name__ == "__main__":
    main()
